"""Draw the Scholium lockup with the wordmark as OUTLINES.

    uv run --project ~/.claude/skills/generating-business-collateral --with uharfbuzz \
        python docs/brand/build_lockup.py

The wordmark is "scholium" in Scholium Display Bold (docs/brand/type/), shaped
with HarfBuzz so the face's own kerning applies, then converted to SVG paths.
It is artwork, not text: no font has to load in the app, the share cards or an
e-mail client, and nothing can fall back to another face.

It sits on the BrandMark grid (apps/web/src/features/ui-kit/brand-mark.tsx:
52 x 54, the bracket's height) by the lockup rules in docs/design.md section 2:
wordmark x-height 0.46 of the lockup height, baseline 0.205 of it above the
bottom edge, pen origin 0.26 of it right of the bracket (the "s" adds its own
side bearing, about 0.05, for an ink gap of about 0.31).

Writes, next to this file:
  scholium-wordmark.json      the wordmark path and metrics, in grid units
  scholium-lockup-light.svg   mark + wordmark, light tokens
  scholium-lockup-dark.svg    mark + wordmark, dark tokens
  scholium-lockup-light.png   1200 px wide, clear space shown, even padding (the app copies it)
  scholium-lockup-dark.png
  scholium-lockup-email.png   64 px tall, light, opaque paper ground: the
                              notification e-mail header shows it at 32 px
"""
from __future__ import annotations

import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
FONT = HERE / "type/fonts/ScholiumDisplay-Bold.otf"
GW, GH = 52, 54                                   # BrandMark glyph grid
X_HEIGHT, BASELINE, GAP = 0.46, 0.205, 0.26       # docs/design.md section 2, of GH
TOPS = [15, 20.6, 26.2, 31.8, 37.4]
THEMES = {
    "light": dict(accent="#2F4BA0", paper="#FBFAF7", note="#FFF6D6", ink="#1B1D22"),
    "dark": dict(accent="#8FA6F0", paper="#14151A", note="#3A3320", ink="#ECEBE6"),
}


def num(v: float) -> str:
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def wordmark() -> dict:
    import uharfbuzz as hb
    from fontTools.pens.boundsPen import BoundsPen
    from fontTools.pens.svgPathPen import SVGPathPen
    from fontTools.pens.transformPen import TransformPen
    from fontTools.ttLib import TTFont

    tt = TTFont(FONT)
    upm = tt["head"].unitsPerEm
    xh = tt["OS/2"].sxHeight
    scale = X_HEIGHT * GH / xh                     # grid units per font unit
    baseline = GH * (1 - BASELINE)                 # SVG y grows downward
    x0 = GW + GAP * GH

    face = hb.Face(hb.Blob.from_file_path(str(FONT)))
    font = hb.Font(face)
    buf = hb.Buffer()
    buf.add_str("scholium")
    buf.guess_segment_properties()
    hb.shape(font, buf, {"kern": True, "liga": False})

    order, gs = tt.getGlyphOrder(), tt.getGlyphSet()
    svg = SVGPathPen(gs, ntos=num)
    bounds = BoundsPen(gs)
    pen_x, kerned = 0, []
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        name = order[info.codepoint]
        t = (scale, 0, 0, -scale, x0 + (pen_x + pos.x_offset) * scale, baseline - pos.y_offset * scale)
        gs[name].draw(TransformPen(svg, t))
        gs[name].draw(TransformPen(bounds, t))
        if pos.x_advance != tt["hmtx"][name][0]:
            kerned.append((name, pos.x_advance - tt["hmtx"][name][0]))
        pen_x += pos.x_advance
    xmin, ymin, xmax, ymax = bounds.bounds
    del xh  # the scale above is derived from it
    return dict(path=svg.getCommands(), font=FONT.name, upm=upm, scale=scale,
                font_size=scale * upm, baseline=baseline, pen_origin_x=x0,
                ink=[round(xmin, 2), round(ymin, 2), round(xmax, 2), round(ymax, 2)],
                view_box=[0, 0, float(num(xmax + 0.005)), GH], kerned=kerned)


def lockup_svg(wm: dict, theme: str) -> str:
    t = THEMES[theme]
    w = wm["view_box"][2]
    lines = "".join(
        f'<rect x="5.5" y="{y}" width="{13 if i == 4 else 25}" height="1.6" rx="0.8" fill="{t["paper"]}"/>'
        for i, y in enumerate(TOPS))
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {num(w)} {GH}" '
            f'width="{num(w)}" height="{GH}" role="img" aria-label="Scholium">\n'
            f'  <rect width="36" height="40" y="7" fill="{t["accent"]}"/>\n  {lines}\n'
            f'  <rect x="39" y="7" width="9" height="40" fill="{t["note"]}"/>\n'
            f'  <path d="M39 0h13v54H39v-4h9V4h-9z" fill="{t["accent"]}"/>\n'
            f'  <path d="{wm["path"]}" fill="{t["ink"]}"/>\n</svg>\n')


def main() -> int:
    import cairosvg
    wm = wordmark()
    (HERE / "scholium-wordmark.json").write_text(json.dumps({
        "about": "The Scholium wordmark as outlines, in BrandMark grid units (the lockup is 54 tall). "
                 "Generated by docs/brand/build_lockup.py from " + wm["font"] + "; do not edit by hand.",
        **{k: wm[k] for k in ("view_box", "path", "ink", "baseline", "pen_origin_x", "font_size", "font")},
    }, indent=2) + "\n")
    for theme in THEMES:
        svg = lockup_svg(wm, theme)
        (HERE / f"scholium-lockup-{theme}.svg").write_text(svg)   # tight: layouts add clear space
        # The reference PNG shows the clear space: half the mark height on every side.
        w, pad = wm["view_box"][2], GH / 2
        padded = svg.replace(f'viewBox="0 0 {num(w)} {GH}" width="{num(w)}" height="{GH}"',
                             f'viewBox="{num(-pad)} {num(-pad)} {num(w + 2 * pad)} {num(GH + 2 * pad)}" '
                             f'width="{num(w + 2 * pad)}" height="{num(GH + 2 * pad)}"', 1)
        assert padded != svg, "clear-space padding did not apply"
        cairosvg.svg2png(bytestring=padded.encode(), write_to=str(HERE / f"scholium-lockup-{theme}.png"),
                         output_width=1200, background_color=THEMES[theme]["paper"])
    cairosvg.svg2png(bytestring=lockup_svg(wm, "light").encode(),
                     write_to=str(HERE / "scholium-lockup-email.png"),
                     output_height=64, background_color=THEMES["light"]["paper"])
    # The rules, measured back off the drawing: x-height from the top of the u's
    # stems (flat, so no overshoot), in grid units.
    from fontTools.pens.boundsPen import BoundsPen
    from fontTools.ttLib import TTFont
    gs = TTFont(FONT).getGlyphSet()
    bp = BoundsPen(gs)
    gs["u"].draw(bp)
    xh_drawn = bp.bounds[3] * wm["scale"]
    print(f"view box 0 0 {wm['view_box'][2]} {GH}   (lockup aspect {wm['view_box'][2] / GH:.3f})")
    print(f"ink x {wm['ink'][0]:.2f} -> {wm['ink'][2]:.2f}; ascender top at y {wm['ink'][1]:.2f} "
          f"(page block top is 7); baseline y {wm['baseline']:.2f}; drawn x-height {xh_drawn:.2f} "
          f"= {xh_drawn / GH:.3f} of the lockup (rule: 0.46)")
    print(f"ink gap bracket -> wordmark: {(wm['ink'][0] - GW) / GH:.3f} of the lockup height")
    print(f"kerning applied by HarfBuzz: {wm['kerned'] or 'none'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
