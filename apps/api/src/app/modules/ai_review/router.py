"""HTTP route for reading a paper's advisory AI pre-review (feature 122).

The module loader mounts this router under ``/v1``, so this package serves:

* ``GET /v1/papers/{id}/ai-reviews`` -- the reports the ``ai_review`` plugin
  appended for the paper, labelled advisory and grouped by agent.

``{id}`` is any spelling :class:`app.modules.catalog.service` accepts -- a
paper ``sch:`` id, a version id (``sch:xxxx-xxxx-xxxx/vN``) or a version cid
-- and the response describes the same *listed* version ``GET
/v1/papers/{id}`` describes.  An unlisted version, an id this node does not
hold and a paper whose review has not been appended yet all answer ``404``:
an AI review is only ever readable for a version that is public.

Reading is anonymous, like reading a record.  Nothing here writes anything:
the endpoint is a pure projection of the ``ai_reviews`` row, so it can never
change ``papers.status`` (feature 122's third criterion).
"""

from __future__ import annotations

from typing import Any, Optional

from fastapi import APIRouter

from app import db

from .models import AIReview, ensure_ai_reviews_table
from .prompt_set import AGENT_NAMES

__all__ = ["ADVISORY_LABEL", "router"]

router = APIRouter(tags=["ai-reviews"])

#: The banner every AI report carries, spelled as the design's UI spells it.
ADVISORY_LABEL = "Advisory. Generated by AI agents. Not a peer review."


def _not_found(identifier: str) -> Any:
    """The ``404`` for an id the catalog does not serve.

    ``app.errors`` and the catalog are imported here rather than at module
    import time: both pull in the app factory, and importing the plugin must
    not change what other plugins have already wired up when it is loaded.
    """
    from app.errors import ProblemException

    return ProblemException(
        404, f"No listed paper {identifier!r} is on this node."
    )


def _review_for(version_cid: str) -> Optional[AIReview]:
    """The stored review for ``version_cid``, or ``None`` when none exists."""
    ensure_ai_reviews_table()
    with db.SessionLocal() as session:
        row = session.query(AIReview).filter_by(version_cid=version_cid).first()
        if row is not None:
            session.expunge(row)
        return row


def _group_by_agent(findings: Any) -> list[dict[str, Any]]:
    """Split ``findings`` into one group per agent, specialists first.

    Every specialist agent gets a group even when it reported nothing, so a
    reader can tell "this agent had no findings" from "this agent did not
    run": the pipeline always runs all four.  A finding naming another agent
    keeps its own group, appended after the specialists, so a future agent is
    shown rather than silently dropped.
    """
    grouped: dict[str, list[dict[str, Any]]] = {name: [] for name in AGENT_NAMES}
    extras: dict[str, list[dict[str, Any]]] = {}
    for finding in findings if isinstance(findings, list) else ():
        if not isinstance(finding, dict):
            continue
        agent = finding.get("agent")
        if not isinstance(agent, str) or not agent.strip():
            agent = "unknown"
        if agent in grouped:
            grouped[agent].append(finding)
        else:
            extras.setdefault(agent, []).append(finding)

    groups = [
        {"agent": name, "name": name, "findings": grouped[name]}
        for name in AGENT_NAMES
    ]
    groups.extend(
        {"agent": name, "name": name, "findings": items}
        for name, items in extras.items()
    )
    return groups


def _report(identifier: str) -> dict[str, Any]:
    """Render the review for the listed version ``identifier`` resolves to."""
    from app.errors import ProblemException
    from app.modules.catalog.service import resolve as resolve_listed

    view = resolve_listed(identifier)
    if view is None:
        raise _not_found(identifier)

    paper = view.paper
    version = view.version
    review = _review_for(version.version_cid)
    if review is None:
        raise ProblemException(
            404, f"No AI pre-review for {identifier!r} yet."
        )

    return {
        "paper": paper.short_id,
        "shortId": paper.short_id,
        "paperCid": paper.paper_cid,
        "versionCid": version.version_cid,
        "version_cid": version.version_cid,
        "version": int(version.n),
        "n": int(version.n),
        "reviewCid": review.review_cid,
        "review_cid": review.review_cid,
        "advisory": True,
        "label": ADVISORY_LABEL,
        "models": list(review.models or []),
        "promptSetHash": review.prompt_set_hash,
        "prompt_set_hash": review.prompt_set_hash,
        "agents": _group_by_agent(review.findings),
    }


@router.get(
    "/papers/{paper_id}/ai-reviews",
    summary="Read the advisory AI pre-review of a listed paper",
)
def get_ai_reviews(paper_id: str) -> dict[str, Any]:
    """Return the paper's advisory AI report, findings grouped by agent."""
    return _report(paper_id)


@router.get(
    "/papers/{paper_id}/v{n}/ai-reviews",
    summary="Read the advisory AI pre-review of one listed paper version",
)
def get_version_ai_reviews(paper_id: str, n: str) -> dict[str, Any]:
    """Return the advisory AI report of version ``n`` of ``paper_id``."""
    return _report(f"{paper_id}/v{n}")
