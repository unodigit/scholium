const test = base.extend<{ passkeys: void }>({
  /**
   * A virtual authenticator on the page: a platform passkey that has a
   * resident credential, verifies the user and is always "touched".
   */
  passkeys: [
    async ({ context, page }, use) => {
      const cdp = await context.newCDPSession(page);
      await cdp.send("WebAuthn.enable");
      const { authenticatorId } = await cdp.send("WebAuthn.addVirtualAuthenticator", {
        options: {
          protocol: "ctap2",
          transport: "internal",
          hasResidentKey: true,
          hasUserVerification: true,
          isUserVerified: true,
          automaticPresenceSimulation: true,
        },
      });
      await use();
      await cdp.send("WebAuthn.removeVirtualAuthenticator", { authenticatorId });
      await cdp.send("WebAuthn.disable");
    },
    { auto: false },
  ],
});

// --- Helpers -----------------------------------------------------------------

interface SeededPaper {
  shortId: string;
  title: string;
  authors: { did: string }[];
}

/** The seeded paper with this title, as the API lists it. */
async function seededPaper(request: APIRequestContext, title: string): Promise<SeededPaper> {
  const response = await request.get(`${fromConfig("E2E_API_URL")}/v1/papers`);
  expect(response.ok()).toBe(true);
  const { items } = (await response.json()) as { items: SeededPaper[] };
  const paper = items.find((item) => item.title === title);
  if (!paper) {
    throw new Error(`the seeded paper ${JSON.stringify(title)} is not on the node`);
  }
  return paper;
}

/**
 * Open a page and wait until it has hydrated, so the first click lands on a
 * live handler rather than on server-rendered markup.
 */
async function visit(page: Page, path: string): Promise<void> {
  await page.goto(path, { waitUntil: "networkidle" });
}

/**
 * Press "Sign in with passkey" on `/signin`. Resolves with the DID that signed
 * in and the access token the node issued for it.
 */
async function signInWithPasskey(page: Page): Promise<{ did: string; accessToken: string }> {
  const challenge = page.waitForRequest((request) => request.url().endsWith("/v1/auth/challenge"));
  const verified = page.waitForResponse((response) => response.url().endsWith("/v1/auth/verify"));
  await page.getByRole("button", { name: "Sign in with passkey" }).click();
  const { did } = (await challenge).postDataJSON() as { did: string };
  const issued = await verified;
  expect(issued.status()).toBe(200);
  const { access_token: accessToken } = (await issued.json()) as { access_token: string };
  return { did, accessToken };
}

/** A first sign-in on this device creates the passkey and the account: `/onboarding`. */
async function createAccount(page: Page): Promise<string> {
  await visit(page, "/signin");
  const { did } = await signInWithPasskey(page);
  await expect(page).toHaveURL(/\/onboarding$/);
  await expect(page.getByRole("heading", { name: "Welcome" })).toBeVisible();
  return did;
}

/**
 * What the reviewer's endorsement is, in Python because that is where the
 * record core (the one signing implementation the API's own checks are written
 * against) lives. It signs in as the seeded reviewer with the key `seed-demo`
 * wrote, signs an `endorsement`, and posts it to the running API.
 */
const ENDORSE = `
import json, sys
from datetime import datetime, timezone

import httpx
from nacl.signing import SigningKey
from scholium_record_core import did_key_from_signing_key, encode_signature, sign_record

keys_file, api, endorsee, category = sys.argv[1:5]
with open(keys_file, encoding="utf-8") as handle:
    key = SigningKey(bytes.fromhex(json.load(handle)["accounts"]["okafor"]["seed"]))
did = did_key_from_signing_key(key)
with httpx.Client(base_url=api, timeout=30) as http:
    nonce = http.post("/v1/auth/challenge", json={"did": did}).json()["nonce"]
    signature = encode_signature(key.sign(nonce.encode("utf-8")).signature)
    verified = http.post("/v1/auth/verify", json={"did": did, "nonce": nonce, "signature": signature})
    verified.raise_for_status()
    record = sign_record(
        {
            "v": 1,
            "type": "endorsement",
            "author": did,
            "created": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "prev": None,
            "body": {"endorsee": endorsee, "category": category, "statement": "Endorsed for the browser journeys."},
            "proofs": [],
        },
        key,
    )
    posted = http.post(
        "/v1/records", json=record, headers={"Authorization": "Bearer " + verified.json()["access_token"]}
    )
    if posted.status_code != 201:
        sys.exit("the node refused the endorsement: %s %s" % (posted.status_code, posted.text))
`;

/** A seeded reviewer endorses `did` in `category`; the account becomes an Author (tier 2). */
function endorse(did: string, category: string): void {
  execFileSync(
    "uv",
    ["run", "--all-packages", "python", "-c", ENDORSE, fromConfig("E2E_DEMO_KEYS"), fromConfig("E2E_API_URL"), did, category],
    { cwd: fromConfig("E2E_API_DIR"), encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] },
  );
}

/**
 * A one-page PDF with real text on it (the node reads the first page to check
 * the title), built by hand so the journey needs no fixture file.
 */
function pdfWithText(lines: string[]): Buffer {
  const escape = (text: string) => text.replace(/[\\()]/g, "\\$&");
  const content = `BT /F1 12 Tf 72 720 Td 16 TL ${lines.map((line) => `(${escape(line)}) Tj T*`).join(" ")} ET`;
  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>",
    `<< /Length ${content.length} >>\nstream\n${content}\nendstream`,
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
  ];
  let pdf = "%PDF-1.4\n";
  const offsets: number[] = [];
  objects.forEach((object, index) => {
    offsets.push(pdf.length);
    pdf += `${index + 1} 0 obj\n${object}\nendobj\n`;
  });
  const xref = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (const offset of offsets) {
    pdf += `${String(offset).padStart(10, "0")} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(pdf, "latin1");
}

