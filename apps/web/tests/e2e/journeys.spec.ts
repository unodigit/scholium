test.describe("signing in", () => {
  test("a member signs in, posts in Discussion and sees the post", async ({ page, request, passkeys }) => {
    void passkeys;
    const paper = await seededPaper(request, META_AGENT.title);
    const post = `A signed post from the browser journeys (${Date.now()}).`;

    // A new account is a Reader; an endorsement makes it an Author (and a Member).
    const did = await createAccount(page);
    endorse(did, "cs.AI");

    // The page load restores the session from the refresh cookie, and the new
    // access token carries the tier the endorsement just granted — no second
    // sign-in is needed.  `#discussion` is a tab address, so landing on it
    // opens Discussion directly.
    await visit(page, "/");
    const paperHref = await page
      .getByRole("link", { name: META_AGENT.title })
      .getAttribute("href");
    if (!paperHref) {
      throw new Error("the seeded paper is not linked from the feed");
    }
    await visit(page, `${paperHref}#discussion`);
    await expect(
      page.getByRole("heading", { name: META_AGENT.title, level: 1 }),
    ).toBeVisible();
    await expect(page.getByRole("tab", { name: "Discussion" })).toHaveAttribute(
      "aria-selected",
      "true",
    );

    await page.getByRole("button", { name: "Start a thread" }).click();
    await page.getByRole("textbox").fill(post);
    const accepted = page.waitForResponse(
      (response) => response.url().includes("/threads") && response.request().method() === "POST",
    );
    await page.getByRole("button", { name: "Sign and submit" }).click();

    // The passkey signs the record and the node accepts it.
    expect((await accepted).status()).toBe(201);
    await expect(page.getByRole("tabpanel").getByText(post)).toBeVisible();

    const threads = await request.get(`${fromConfig("E2E_API_URL")}/v1/papers/${encodeURIComponent(paper.shortId)}/threads`);
    expect(await threads.text()).toContain(post);
  });
});

test.describe("publishing", () => {
  test("an endorsed author uploads a PDF, fills in the details, signs, and reaches the status tracker", async ({
    page,
    passkeys,
  }) => {
    void passkeys;
    const title = `Browser journeys for a signed preprint node ${Date.now()}`;

    const did = await createAccount(page);
    endorse(did, "cs.AI");
    // A page load restores the session (and the tier the endorsement granted).
    await visit(page, "/submit");

    // 1 Files
    await page.locator('input[type="file"]').first().setInputFiles({
      name: "paper.pdf",
      mimeType: "application/pdf",
      buffer: pdfWithText([title, "A manuscript for the browser journeys."]),
    });
    await expect(page.getByText("1 of 1 file uploaded")).toBeVisible();
    await page.getByRole("button", { name: "Continue to Details" }).click();

    // 2 Details
    await page.getByLabel("Title", { exact: true }).fill(title);
    await page.getByLabel("Abstract", { exact: true }).fill("A signed preprint node, driven end to end through a real browser.");
    await page.getByRole("button", { name: /^cs\.AI/ }).first().click();
    await page.getByRole("button", { name: /^Continue to Authors/ }).click();

    // 3 Authors: the submitter is author 1 and needs a role.
    await page.getByRole("button", { name: /^Conceptualization/ }).click();
    await page.getByRole("button", { name: /^Continue to Checks/ }).click();

    // 4 Checks run on the signed version, so there is nothing to wait for yet.
    await page.getByRole("button", { name: /^Continue to Sign/ }).click();

    // 5 Sign: the genesis, the manifest and the version are each signed behind
    // a passkey prompt and posted to the node.
    const recordStatuses: number[] = [];
    page.on("response", (response) => {
      if (response.url().endsWith("/v1/records") && response.request().method() === "POST") {
        recordStatuses.push(response.status());
      }
    });
    await page.getByRole("button", { name: "Sign and submit" }).click();

    // Then the status tracker: the version is submitted and waits for the
    // authors' consents (here, just the submitter's own).
    const tracker = page.getByRole("region", { name: "Status tracker" });
    await expect(tracker).toBeVisible();
    await expect(tracker.getByRole("listitem").filter({ hasText: /^Submitted/ })).toBeVisible();
    await expect(tracker.getByRole("list", { name: "Co-author consents" })).toBeVisible();

    expect(recordStatuses.length).toBeGreaterThanOrEqual(3);
    expect(recordStatuses.every((status) => status === 201)).toBe(true);
  });
});

test.describe("the dashboard", () => {
  test("/me loads saved searches and follows without errors", async ({ page, request, passkeys }) => {
    void passkeys;
    // Any API answer of 400 or more while the page is used is a failure.
    const api = fromConfig("E2E_API_URL");
    const failures: string[] = [];
    const answered = new Set<string>();
    page.on("response", (response) => {
      if (!response.url().startsWith(`${api}/`)) return;
      const call = `${response.request().method()} ${new URL(response.url()).pathname}`;
      answered.add(call);
      if (response.status() >= 400) {
        // A page load asks the cookie for a session.  Before sign-in there is
        // none, and 401/422 is the API's normal "no session" answer — not a
        // failure of the dashboard.
        const noSession =
          call === "POST /v1/auth/refresh" &&
          (response.status() === 401 || response.status() === 422);
        if (!noSession) failures.push(`${call} -> ${response.status()}`);
      }
    });

    // Follow a category the way onboarding offers it.
    await createAccount(page);
    await page.getByRole("group", { name: "Categories to follow" }).getByRole("button", { name: "cs.AI" }).click();
    const followed = page.waitForResponse(
      (response) => response.url().endsWith("/v1/me/follows/cs.AI") && response.request().method() === "PUT",
    );
    await page.getByRole("button", { name: "Save categories" }).click();
    expect((await followed).status()).toBe(204);

    // The dashboard loads every section, saved searches included.  Opening
    // /me as a page load restores the session from the cookie first.
    const refreshed = page.waitForResponse((response) =>
      response.url().endsWith("/v1/auth/refresh"),
    );
    await visit(page, "/me");
    const { access_token: accessToken } = (await (
      await refreshed
    ).json()) as {
      access_token: string;
    };
    await expect(page.getByRole("heading", { name: "Me", level: 1 })).toBeVisible();
    await expect(page.getByText("Loading your dashboard…")).toHaveCount(0);
    await expect(page.getByRole("region", { name: "Saved searches" })).toContainText("You have no saved searches yet.");
    // Inside `main`: Next's route announcer is also a `role="alert"`, outside it.
    await expect(page.getByRole("main").getByRole("alert")).toHaveCount(0);
    expect(answered).toContain("GET /v1/me/saved-searches");
    expect(failures).toEqual([]);

    // And the follow is what the node serves back for this account, read with
    // the token this sign-in was given (no page reads this route yet).
    const follows = await request.get(`${api}/v1/me/follows`, { headers: { Authorization: `Bearer ${accessToken}` } });
    expect(follows.status()).toBe(200);
    expect(await follows.json()).toEqual({ categories: ["cs.AI"] });
  });
});
