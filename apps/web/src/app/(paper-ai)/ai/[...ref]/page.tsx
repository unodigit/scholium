import type { Metadata } from "next";
import { cache } from "react";

import { AiTab } from "../../../../features/paper-ai";
import {
  PaperRefError,
  refFromSegments,
  type PaperRef,
} from "../../../../features/paper-proof";
import { loadPaper } from "../../../../features/search-page/paper";

interface AiPageProps {
  /** `/ai/k3f9-q2xz-7mwd` or `/ai/k3f9-q2xz-7mwd/v2` (Next 15: a promise). */
  params: Promise<{ ref: string[] }>;
}

type Parsed = { ref: PaperRef } | { error: string };

function parse(segments: string[]): Parsed {
  try {
    return { ref: refFromSegments(segments) };
  } catch (error) {
    return {
      error:
        error instanceof PaperRefError
          ? error.message
          : "That is not a paper id.",
    };
  }
}

/**
 * The paper's title, read once per request and never a reason to fail the
 * page: a node that cannot answer still shows the advisory header.
 */
const readPaperTitle = cache(
  async (shortId: string, version: number | null): Promise<string | null> => {
    try {
      const paper = await loadPaper({ id: shortId, version });
      return paper.title;
    } catch {
      return null;
    }
  },
);

export async function generateMetadata({ params }: AiPageProps): Promise<Metadata> {
  const parsed = parse((await params).ref);
  if (!("ref" in parsed)) {
    return {
      title: "AI pre-review",
      description:
        "The advisory AI pre-review of a Scholium paper: findings grouped by agent, each with its evidence. Generated by AI agents; not a peer review.",
    };
  }
  // Like /reviews, /proof and /meta, the title names the paper being advised
  // on; the root layout's template adds " · Scholium". The id is a fallback
  // only, for a node that cannot answer, never the reader's title.
  const title = await readPaperTitle(parsed.ref.shortId, parsed.ref.version);
  return {
    title:
      title !== null
        ? `AI pre-review · ${title}`
        : `AI pre-review of ${parsed.ref.schId}`,
    description:
      "The advisory AI pre-review of a Scholium paper: findings grouped by agent, each with its evidence. Generated by AI agents; not a peer review.",
  };
}

/**
 * `/ai/{id}[/v{n}]` — the AI pre-review tab on a page of its own.
 *
 * The URL mirrors the paper page's (`/p/{id}[/v{n}]`, docs/design.md §4), so
 * the advisory report is one path segment away from the paper it advises on.
 * The page only reads the URL; the report is fetched by the tab in the
 * reader's browser, and the first HTML already carries the advisory banner —
 * the label is never delayed behind a request.
 */
export default async function AiPage({ params }: AiPageProps) {
  const parsed = parse((await params).ref);

  // Like /reviews, /proof, /meta and /discussion: the paper being advised on
  // is named and linked, so the reader is one click from it.
  const paperTitle =
    "ref" in parsed
      ? await readPaperTitle(parsed.ref.shortId, parsed.ref.version)
      : null;
  const bare =
    "ref" in parsed
      ? parsed.ref.shortId.trim().replace(/^sch:/i, "").split("/")[0]
      : "";

  return (
    <>
      <header className="pai-header">
        {paperTitle ? (
          <p className="pai-paper">
            <a href={`/p/${encodeURIComponent(bare)}`}>{paperTitle}</a>
          </p>
        ) : null}
        <p className="pai-kicker mono-id">
          scholium / ai{"ref" in parsed ? ` / ${parsed.ref.schId}` : ""}
        </p>
        <h1 className="pai-title">AI pre-review</h1>
        <p className="pai-lede">
          An advisory report generated by AI agents once a version is listed.
          It never decides anything about the paper; authors can rebut each
          finding and reviewers can mark it confirmed or wrong.
        </p>
      </header>

      {"ref" in parsed ? (
        <AiTab paperId={parsed.ref.schId} />
      ) : (
        <div className="pai-notice" role="alert">
          <p className="pai-notice__title">That is not a paper id</p>
          <p className="pai-notice__text">{parsed.error}</p>
        </div>
      )}
    </>
  );
}
