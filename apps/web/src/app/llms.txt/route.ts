import { resolveSiteUrl } from "../site-metadata";

/**
 * `GET /llms.txt`, served by Next from this file as a route handler.
 *
 * Answer engines read `/llms.txt` (the llms.txt convention) to find out what a
 * site is and which pages matter before they fetch anything. The text is the
 * markdown in `docs/homepage/llms.txt` — title, one-line blockquote summary,
 * the key facts, the pages and the name — kept here as a constant because the
 * route must ship inside the standalone server, where `docs/` does not exist.
 * A test reads the document and compares, so the two cannot drift.
 *
 * The document's links are written root-relative; {@link absoluteLinks} makes
 * them absolute from {@link resolveSiteUrl}, the one source of the site's
 * origin. No domain is hard-coded here: the same text serves every deployment.
 */

/**
 * The markdown body, word for word from `docs/homepage/llms.txt`, with its
 * links root-relative instead of pinned to one domain.
 */
export const LLMS_TXT_MARKDOWN = `# Scholium

> Scholium is a free preprint and open peer-review network. Every paper, version and review is a signed, content-addressed record, so anyone can check who wrote what, and when, in the browser or offline, without trusting the operator.

Scholium works alongside existing preprint servers such as arXiv; papers can be imported from arXiv and claimed by their authors. It is not a journal: it lists, reviews and badges papers, and it does not accept or reject science.

## Key facts

- Type: preprint and open peer-review network
- Cost: free to read and to publish; no submission fee
- Licence: CC BY 4.0 by default, chosen at submission
- Identifiers: one stable ID per paper and per version, e.g. \`sch:k3f9-q2xz-7mwd/v3\`; earlier versions stay resolvable
- Sign-in: passkey plus ORCID iD; the signing key lives on the author's device and Scholium never sees it
- Provenance: the author's browser fingerprints each file and signs each version; each version records the fingerprint of the one before
- Co-authors: every listed co-author signs consent before a version is listed
- Review: formal reviews against a six-criterion rubric (soundness, evidence, reproducibility, novelty, clarity, limitations) with confidence and recommendation
- Reviewer identity: anonymous to authors but accountable; one formal review per person per paper; co-authors and conflicts of interest are refused
- Sealed reports: reports stay hidden until two reviewers have committed theirs, or 21 days pass
- Discussion: open threads and paragraph-level annotations; helpful votes only order a thread and never change a paper's status
- AI pre-review: an advisory report from AI agents, aimed at about one hour after listing, with evidence links; labelled "Advisory. Generated by AI agents. Not a peer review."; never changes status
- Moderation: volunteer subject moderators, a published policy, a 48-hour decision target; every decision is a signed public record naming a policy clause
- Corrections and retractions: signed records shown as a banner on every version
- Verification: in the browser (Proof tab, /verify) or offline with \`scholium verify <archive.car>\`
- Export: full paper archives that verify offline; BibTeX and RIS
- Account recovery: three of five guardians, then a 72-hour safety window the owner can cancel
- Token or cryptocurrency: none, and none planned
- Planned (not yet available): public timestamp anchoring, DOIs, independent library nodes

## Pages

- [Homepage](/): what Scholium is, how it works, and answers to common questions
- [Papers](/papers): the latest and reviewed preprints, by category
- [Search papers](/search): full-text search with filters for status, category and papers with code
- [Verify a file](/verify): check a PDF against what its authors signed
- [Network status](/network): the node's standing, log head and moderation statistics
- [Moderation policies](/policies): the policy clauses that moderation decisions cite

## Name

A scholium (plural scholia) is an explanatory note written in the margin of a scholarly text. Scholium keeps a paper and its margin together: reviews, notes and corrections stay beside the text they are about.
`;

/**
 * Make every root-relative markdown link absolute against `siteUrl`.
 *
 * Only the `](…)` destination is rewritten, so inline code and prose that
 * happens to start with a slash are untouched.
 */
export function absoluteLinks(markdown: string, siteUrl: string): string {
  const base = siteUrl.replace(/\/+$/, "");
  return markdown.replace(
    /\]\((\/[^)\s]*)\)/g,
    (_match, path: string) => `](${base}${path})`,
  );
}

/** The body `/llms.txt` answers with. */
export function getLlmsTxt(siteUrl: string = resolveSiteUrl()): string {
  return absoluteLinks(LLMS_TXT_MARKDOWN, siteUrl);
}

/**
 * The crawler-facing text does not vary by request, so render it once at
 * build time rather than on every fetch.
 */
export const dynamic = "force-static";

export async function GET(): Promise<Response> {
  return new Response(getLlmsTxt(), {
    status: 200,
    headers: { "content-type": "text/plain; charset=utf-8" },
  });
}
