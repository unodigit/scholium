// @vitest-environment jsdom
import { cleanup, render, screen, waitFor } from "@testing-library/react";
import { afterEach, describe, expect, it } from "vitest";

import { OpenReviewSection } from "./open-review";
import { AiPrereviewSection } from "./ai-prereview";

afterEach(() => {
  cleanup();
});

describe("OpenReviewSection", () => {
  it("exposes the rubric as role=img with its text equivalent", () => {
    render(<OpenReviewSection />);
    const img = screen.getByRole("img", { name: /soundness 4 of 5/i });
    expect(img).toBeTruthy();
    expect(img.getAttribute("aria-label")).toContain("Confidence high");
  });

  it("sealed reports switch from Committed to Revealed", async () => {
    const { container } = render(<OpenReviewSection />);
    expect(screen.getAllByText("Committed")).toHaveLength(2);
    const sealed = container.querySelector("#sealed");
    expect(sealed?.classList.contains("open")).toBe(false);

    await waitFor(
      () => {
        expect(container.querySelector("#sealed")?.classList.contains("open")).toBe(true);
      },
      { timeout: 2500 },
    );
  });
});

describe("AiPrereviewSection", () => {
  it("renders the advisory banner text", () => {
    render(<AiPrereviewSection />);
    expect(
      screen.getByText("Advisory. Generated by AI agents. Not a peer review."),
    ).toBeTruthy();
  });
});